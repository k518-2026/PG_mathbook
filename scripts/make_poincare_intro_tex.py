def clean_lecture(text):
    # Escape standalone & in text
    text = text.replace('&', r'\&')

    # Strip markdown headers into bold or section titles
    lines = text.split("\n")
    cleaned = []
    for l in lines:
        if l.startswith("### "):
            cleaned.append(r"\par\medskip\noindent\textbf{\large " + l[4:].strip() + r"}\par\smallskip")
        elif l.startswith("#### "):
            cleaned.append(r"\par\smallskip\noindent\textbf{" + l[5:].strip() + r"}\par")
        elif l.startswith("## "):
            cleaned.append(r"\par\medskip\noindent\textbf{\Large " + l[3:].strip() + r"}\par\smallskip")
        else:
            cleaned.append(l)
    res = "\n".join(cleaned)
    # Convert bold **text** to \textbf{text}
    res = re.sub(r'\*\*(.+?)\*\*', r'\\textbf{\1}', res)
    # Remove remaining markdown bullets
    res = re.sub(r'^\*\s+', r'・', res, flags=re.MULTILINE)
    res = re.sub(r'^\-\s+', r'・', res, flags=re.MULTILINE)
    return res

