LM_STUDIO_URL = "http://192.168.128.16:1234/v1/chat/completions"
MODEL_NAME = "google/gemma-3-4b"

def query_gemma(prompt, max_tokens=1200, temperature=0.7, retries=3):
    headers = {"Content-Type": "application/json"}
    payload = {
        "model": MODEL_NAME,
        "messages": [
            {"role": "user", "content": prompt}
        ],
        "temperature": temperature,
        "max_tokens": max_tokens
    }
    for attempt in range(retries):
        try:
            req = urllib.request.Request(LM_STUDIO_URL, data=json.dumps(payload).encode('utf-8'), headers=headers)
            with urllib.request.urlopen(req, timeout=120) as res:
                data = json.loads(res.read().decode('utf-8'))
                return data['choices'][0]['message']['content'].strip()
        except Exception as e:
            print(f"[Gemma API] Attempt {attempt+1} failed: {e}")
            time.sleep(3)
    return ""

def clean_for_latex(text):
    """Clean plain text generated by LLM for safe inclusion in LaTeX text paragraphs."""
    # Replace markdown headers and bolding
    text = text.replace('**', '')
    text = text.replace('###', '')
    text = text.replace('##', '')
    text = text.replace('#', '')
    # Replace special chars unless part of math
    text = text.replace('&', '\\&')
    text = text.replace('%', '\\%')
    text = text.replace('_', '\\_')
    text = text.replace('$', '\\$')
    return text

